-- ===========================================================
-- V4 - Criação da tabela de doações
-- ===========================================================
-- Por que V4: a V2 é a tabela produtos da A1 (branch avaliacao1, PR #13
-- ainda sem merge) e a V3 é a de doadores (Etapa 7).
--
-- Base: o script de referência da Aula 05 (mob programming). Mudanças:
-- - CHECK no tipo, com os valores do enum TipoDoacao (como o CHECK da V3);
-- - CHECK no valor: quando vier, maior que zero;
-- - índice também em id_doador, e nomes no padrão idx_<tabela>_<coluna>
--   da Aula 04;
-- - FK com o nome no plural da tabela (fk_doacoes_doador) e criada por
--   último (ver o ALTER TABLE no fim).
-- O banco é a fonte da verdade: a Entity Doacao só espelha estes números.
-- Chave primária no padrão da disciplina: prefixo id_.

CREATE TABLE doacoes (
    id_doacao   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doador   BIGINT       NOT NULL,
    data_doacao DATE         NOT NULL,
    -- DECIMAL(10,2): até 99.999.999,99, com os centavos exatos. Um tipo de
    -- ponto flutuante (REAL, DOUBLE) guardaria valores como 0,10 só aproximados.
    valor       DECIMAL(10,2),
    tipo        VARCHAR(20)  NOT NULL,
    descricao   VARCHAR(500),

    -- Num CHECK, NULL não reprova: a doação sem valor (roupa, alimento)
    -- passa, e valor 0 ou negativo é recusado.
    CONSTRAINT ck_doacoes_valor CHECK (valor > 0),
    -- Mesmos valores do enum TipoDoacao, gravado como texto. Barra um tipo
    -- estranho mesmo quando alguém grava sem passar pela API.
    CONSTRAINT ck_doacoes_tipo CHECK (tipo IN ('ALIMENTO', 'ROUPA', 'FINANCEIRA'))
);

-- data_doacao: filtro por período da listagem (dataInicio e dataFim no
-- GET /api/v1/doacoes).
CREATE INDEX idx_doacoes_data_doacao ON doacoes (data_doacao);

-- tipo: filtro da listagem.
CREATE INDEX idx_doacoes_tipo ON doacoes (tipo);

-- id_doador: o PostgreSQL não cria índice para a coluna de uma FK. Sem ele,
-- achar as doações de um doador leria a tabela inteira.
CREATE INDEX idx_doacoes_id_doador ON doacoes (id_doador);

-- FK depois dos índices, de propósito: o H2 cria sozinho um índice para a
-- coluna da FK quando não encontra um pronto. Declarada dentro do CREATE
-- TABLE, a FK ganharia esse índice automático e o idx_doacoes_id_doador
-- seria o segundo índice na mesma coluna. Criada aqui, o H2 reaproveita o
-- idx_doacoes_id_doador.
ALTER TABLE doacoes
    ADD CONSTRAINT fk_doacoes_doador
    FOREIGN KEY (id_doador) REFERENCES doadores (id_doador);

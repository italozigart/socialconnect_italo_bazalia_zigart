-- ===========================================================
-- V3 - Criação da tabela de doadores
-- ===========================================================
-- Por que V3 e não V2: a V2 é a tabela produtos da A1 (branch avaliacao1,
-- PR #13 ainda sem merge). Com números diferentes, as duas convivem se a A1
-- entrar na main; o Flyway aceita a falta de uma versão no meio.
--
-- Colunas da dinâmica da Aula 04 (nome, tipo, email, telefone) e tamanhos
-- do contrato (DoadorRequest no docs/openapi.yaml). O banco é a fonte da
-- verdade: a Entity Doador só espelha estes números.
-- Chave primária no padrão da disciplina: prefixo id_.

CREATE TABLE doadores (
    id_doador BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(200) NOT NULL,
    tipo      VARCHAR(20)  NOT NULL,
    -- 254 caracteres: o maior endereço de e-mail que o padrão permite (RFC 5321).
    email     VARCHAR(254),
    telefone  VARCHAR(20),

    -- Mesmos valores do enum TipoDoador, gravado como texto. Barra um tipo
    -- estranho mesmo quando alguém grava sem passar pela API.
    CONSTRAINT ck_doadores_tipo CHECK (tipo IN ('PESSOA_FISICA', 'PESSOA_JURIDICA'))
);

-- A listagem (GET /api/v1/doadores) ordena por nome quando o cliente não
-- manda sort. Com o índice, o banco lê os nomes já em ordem, em vez de
-- ordenar a tabela inteira a cada página.
CREATE INDEX idx_doadores_nome ON doadores (nome);
